#!/usr/bin/env python3
"""A speech sidecar that announces nothing, so something else can.

Point FPVTrackside's Live Speech at this (Settings -> Live Speech -> Server
Script) when dd-pits is doing the talking. FPVTrackside then keeps deciding
WHAT to say and keeps writing every line to its log, but produces no sound and
loads no models.

This exists because the obvious ways to silence it are both wrong on macOS:

  - Mute sits on SpeechManager's ENQUEUE path and returns before Speak() is
    ever called, so the "SpeechManager: TTS (...)" line is never written.
    Anything reading that log to voice the calls elsewhere goes deaf along with
    the speakers — and it is exactly the operator-triggered calls that are lost,
    the ones no timing data can reveal: Hurry Up, In The Hole, Next Up.

  - Volume 0 does nothing here. MacSpeaker.SetVolume is an empty stub and
    Speak() shells out to /usr/bin/say, which takes no volume argument, so the
    call plays at full system volume whatever is configured.

Speaking through a sidecar that discards its input is the only one of the three
that silences the audio while leaving the decision and the log intact — and it
is configuration, not a code change.

The protocol is FPVTrackside's, kept deliberately minimal: READY once, DONE per
spoken line, SAID for a commentary request. Nothing is imported beyond the
standard library, so it starts instantly and holds no GPU or audio device.
"""

import json
import os
import urllib.request
import sys
import time

# How long a line "takes to speak", used to hold the DONE reply.
#
# This is not cosmetic. FPVTrackside starts the race clock from the
# speech-FINISHED callback:
#
#     SoundManager.StartRaceIn(delay, () => { ... StartRace(); })
#
# so replying instantly collapses the start timeline and the tone fires early —
# its own source warns about exactly this for a disabled sound ("the
# delayed-start timeline collapses"). Reporting a realistic duration keeps race
# timing identical to a venue speaking for itself.
#
# Calibrated against the real clips: "Arm your quads. Starting on the tone in
# less than 5" is ten words and renders at 2.9s, i.e. ~0.29s per word.
SECONDS_PER_WORD = 0.29
SPEECH_OVERHEAD = 0.25

# Where to ask whether dd-pits is STILL SPEAKING.
#
# The estimate above is only a fallback. It is a word count, and the real audio
# is generated by a model whose pace it cannot know — measured against the
# countdown, the estimate expired while dd-pits was still saying "starting on
# the tone in less than five", so FPVTrackside started the race under its own
# countdown. Asking the bus directly replaces the guess with the fact.
SPEAKING_URL = os.environ.get("DD_PITS_SPEAKING_URL", "http://127.0.0.1:8088/speaking")

# Never wait longer than this for the bus to fall quiet.
#
# HARD CEILING, set by FPVTrackside rather than chosen here: its live-speech
# speaker gives up on a line after 8s (LiveSpeechSpeaker.SpeakTimeout) and falls
# back to the SYSTEM voice. Waiting past that does not delay the race — it makes
# the operating system read the line out in its own robotic voice, on top of
# dd-pits saying the same thing. Both were heard live.
#
# Six seconds leaves room for the reply to travel back before that fires.
MAX_SPEECH_WAIT = 6.0

# Which lines are held for the real audio.
#
# Only the ones that GATE THE RACE START are worth waiting on: FPVTrackside
# starts its clock from the countdown's speech-finished callback, so that is
# the one line where replying early moves the start. Every other line is
# reported on the estimate, as before.
#
# Holding all of them was measured as actively harmful: FPVTrackside's speech
# queue is serial, so each wait delays the next line reaching its log — which is
# where dd-pits reads lap calls from — and a busy bus pushed lines past the 8s
# timeout into the system voice.
GATE_PATTERNS = [p.strip().lower() for p in os.environ.get(
    "DD_PITS_GATE_LINES", "on the tone;arm your quads").split(";") if p.strip()]


def gates_the_start(text):
    low = text.lower()
    return any(p in low for p in GATE_PATTERNS)

# How long the bus may be quiet before a line counts as finished. A cue can be
# between fragments while a call is still being streamed, so a single quiet
# reading is not proof it has stopped.
QUIET_CONFIRM = 0.20

# How long to wait for dd-pits to START speaking before giving up on it.
#
# Deliberately SHORT, and the reason is not obvious. FPVTrackside's speech queue
# is serial: it does not send the next line until this one replies. Every line
# dd-pits chooses not to say — a superseded relay, a switched-off sound — would
# otherwise stall that queue for the whole wait, and since the relay path reads
# lap calls out of FPVTrackside's LOG, a stall here delays the calls themselves.
# Fixing the countdown at the cost of lap-call latency would be a poor trade.
#
# One second covers a warm generation (measured 100-600ms) and the countdown in
# particular is normally served from cache. A line that takes longer to start
# falls back to the estimate, which is what happened before this existed.
START_WAIT = 1.0


def speech_duration(text):
    """Roughly how long this line would take to say."""
    words = len(text.split())
    if words == 0:
        return 0.0
    return SPEECH_OVERHEAD + words * SECONDS_PER_WORD


def bus_is_speaking():
    """Is dd-pits speaking? None when it cannot be reached."""
    try:
        with urllib.request.urlopen(SPEAKING_URL, timeout=0.5) as r:
            return json.loads(r.read().decode("utf-8")).get("speaking", False)
    except Exception:
        return None


def wait_until_spoken(text):
    """Block until dd-pits has finished saying this line.

    Falls back to the word-count estimate whenever the bus cannot be reached,
    so a venue running FPVTrackside without dd-pits behaves exactly as before.
    """
    estimate = speech_duration(text)
    deadline = time.time() + MAX_SPEECH_WAIT

    # WAIT FOR IT TO START, then wait for it to stop.
    #
    # dd-pits learns about this line from FPVTrackside's log and has to
    # generate it, so the bus is still idle for a moment after the request.
    # A fixed pause before polling is a race: when generation takes longer
    # than the pause, the first reading is "idle" and this returns before a
    # word has been said — exactly the failure it exists to prevent.
    started = False
    start_deadline = time.time() + START_WAIT
    while time.time() < start_deadline:
        speaking = bus_is_speaking()
        if speaking is None:
            break            # no dd-pits: fall through to the estimate
        if speaking:
            started = True
            break
        time.sleep(0.05)

    if not started:
        # Either dd-pits is not there, or it decided to say nothing (a call it
        # derives itself, or one that is switched off). Neither is a reason to
        # hold the race up, so serve out the estimate and let it start.
        remaining = estimate - (time.time() - (deadline - MAX_SPEECH_WAIT))
        if remaining > 0:
            time.sleep(remaining)
        return

    quiet_since = None
    while time.time() < deadline:
        speaking = bus_is_speaking()
        if speaking is None:
            # No dd-pits: serve out the estimate and behave as before.
            remaining = estimate - (time.time() - (deadline - MAX_SPEECH_WAIT))
            if remaining > 0:
                time.sleep(remaining)
            return
        if speaking:
            quiet_since = None
        else:
            if quiet_since is None:
                quiet_since = time.time()
            elif time.time() - quiet_since >= QUIET_CONFIRM:
                return
        time.sleep(0.05)


def main():
    # The handshake. Anything else is a reply to a specific request.
    print("READY", flush=True)

    for line in sys.stdin:
        # rstrip("\r\n"), not just "\n": the caller may be a Windows process,
        # where WriteLine sends CRLF. A surviving carriage return rides into the
        # spoken text and the cache key, where it is invisible and breaks both.
        line = line.rstrip("\r\n")
        if not line:
            continue

        cmd, _, _ = line.partition(" ")
        cmd = cmd.upper()

        if cmd in ("SPEAK", "SPEAKB"):
            # Held for as long as saying it would have taken.
            #
            # The caller blocks on this reply AND starts the race from it, so an
            # instant answer does not merely look wrong — it moves the start.
            # Sleeping here reproduces the timing of a speaker without producing
            # any sound.
            _, _, text = line.partition(" ")
            if gates_the_start(text):
                wait_until_spoken(text)
            else:
                time.sleep(speech_duration(text))
            print("DONE", flush=True)
        elif cmd == "COMMENT":
            # An empty answer, not a missing one: the caller distinguishes "no
            # line to say" from "the sidecar never replied", and only the first
            # is a normal outcome.
            print("SAID ", flush=True)
        elif cmd == "QUIT":
            break
        # STOP, VOLUME and PING expect no reply. Answering them would leave an
        # unread line in the pipe, which the next request would consume as ITS
        # reply — desynchronising the protocol for good.

    return 0


if __name__ == "__main__":
    sys.exit(main())
